import sqlite3
from datetime import datetime, timedelta

DB_NAME = "bot_users.db"

def init_db():
    conn = sqlite3.connect(DB_NAME)
    c = conn.cursor()
    c.execute('''
        CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY,
            free_downloads INTEGER DEFAULT 0,
            vip_until TEXT
        )
    ''')
    conn.commit()
    conn.close()

def check_user_access(user_id: int):
    conn = sqlite3.connect(DB_NAME)
    c = conn.cursor()
    c.execute("SELECT free_downloads, vip_until FROM users WHERE user_id = ?", (user_id,))
    row = c.fetchone()
    
    now = datetime.now()
    
    if not row:
        c.execute("INSERT INTO users (user_id, free_downloads) VALUES (?, 0)", (user_id,))
        conn.commit()
        conn.close()
        return True, "free", 2

    free_downloads, vip_until_str = row
    
    if vip_until_str:
        vip_until = datetime.strptime(vip_until_str, "%Y-%m-%d %H:%M:%S")
        if now < vip_until:
            conn.close()
            return True, "vip", vip_until_str
            
    if free_downloads < 2:
        remaining = 2 - free_downloads
        conn.close()
        return True, "free", remaining

    conn.close()
    return False, "expired", 0

def register_download(user_id: int):
    conn = sqlite3.connect(DB_NAME)
    c = conn.cursor()
    c.execute("UPDATE users SET free_downloads = free_downloads + 1 WHERE user_id = ?", (user_id,))
    conn.commit()
    conn.close()

def activate_vip(user_id: int, days: int = 15):
    conn = sqlite3.connect(DB_NAME)
    c = conn.cursor()
    new_vip_date = (datetime.now() + timedelta(days=days)).strftime("%Y-%m-%d %H:%M:%S")
    c.execute('''
        INSERT INTO users (user_id, vip_until) VALUES (?, ?)
        ON CONFLICT(user_id) DO UPDATE SET vip_until = excluded.vip_until
    ''', (user_id, new_vip_date))
    conn.commit()
    conn.close()
    return new_vip_date
